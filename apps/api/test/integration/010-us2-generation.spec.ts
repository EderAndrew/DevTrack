import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { AiOperationsService } from "../../src/modules/ai/operations/ai-operations.service";
import { EXERCISE_GENERATOR_KEY } from "../../src/modules/exercise-ai/definitions/exercise-generator";
import { validGeneratedBatch } from "../fixtures/exercise-generation/valid-batch";
import { type AiTestApp, drain, resetAiDb } from "../helpers/ai";
import { batchRequest, createExerciseAiApp, requestBatch, scriptGeneration, TEST_EXERCISE_MODEL_CONFIG } from "../helpers/exercise-ai";
import { type ConfirmedTopic, createConfirmedTopic, languageId } from "../helpers/exercises";
import { createSubject, createSyllabusDocument, createUser, loginAs, type TestUser } from "../helpers/factories";
import { api, testConfig } from "../helpers/test-app";

/**
 * 010/US2 — "Criar com IA": a batch on a topic of the teacher's confirmed syllabus, generated by
 * the real `exercise-generator` through the AI foundation (fake provider), materialized as DRAFT
 * exercises in the transaction that completes the execution (010/FR-017–FR-025).
 */

const limits = (overrides: Partial<ReturnType<typeof testConfig>["rateLimit"]> = {}) => ({
  rateLimit: { ...testConfig().rateLimit, aiExecutionsPerMinute: 100, aiAgentPerHour: 100, exerciseAiPerHour: 100, ...overrides },
});

describe("010/US2 pedir exercícios à IA a partir de um tópico", () => {
  let t: AiTestApp;
  let teacher: TestUser;
  let cookie: string;
  let topic: ConfirmedTopic;

  beforeAll(async () => {
    t = await createExerciseAiApp({ config: limits() });
  });
  afterAll(() => t.close());

  beforeEach(async () => {
    await resetAiDb(t);
    teacher = await createUser(t, { roles: ["TEACHER"] });
    cookie = await loginAs(t, teacher);
    topic = await createConfirmedTopic(t, teacher.id, { languageKey: "java" });
  });

  const nothingRequested = async () => {
    expect(await t.prisma.exerciseGenerationBatch.count()).toBe(0);
    expect(await t.prisma.aiExecution.count()).toBe(0);
    expect(t.provider.requests).toHaveLength(0);
  };

  describe("010/US2-1 010/SC-002 pedido válido → lote PENDING, depois GENERATED com a distribuição pedida", () => {
    it("10 exercícios (3 perguntas, 4 múltipla escolha, 3 código) com 2 pegadinhas, Intermediário, em Java", async () => {
      const body = batchRequest(topic, {
        total: 10,
        types: ["OPEN_ANSWER", "MULTIPLE_CHOICE", "CODE"],
        distribution: { mode: "MANUAL", counts: { OPEN_ANSWER: 3, MULTIPLE_CHOICE: 4, CODE: 3 } },
        trickQuestions: 2,
      });
      const res = await requestBatch(t, cookie, body);
      expect(res.status).toBe(202);
      expect(res.body).toMatchObject({
        status: "PENDING",
        topic: { syllabusItemId: topic.itemId, itemText: "Herança e polimorfismo", subjectName: topic.subject.name },
        difficulty: "INTERMEDIATE",
        total: 10,
        counts: { OPEN_ANSWER: 3, MULTIPLE_CHOICE: 4, CODE: 3 },
        trickQuestions: 2,
        language: { name: "Java" },
        distribution: "MANUAL",
        generatedAt: null,
        pendingReview: 0,
      });
      const batchId = res.body.id as string;
      const execution = await t.prisma.aiExecution.findFirstOrThrow();
      expect(execution).toMatchObject({ agentKey: EXERCISE_GENERATOR_KEY, resourceType: "EXERCISE_GENERATION_BATCH", resourceId: batchId, status: "QUEUED" });
      expect((await t.prisma.exerciseGenerationBatch.findUniqueOrThrow({ where: { id: batchId } })).aiExecutionId).toBe(execution.id);
      const requested = await t.prisma.auditEvent.findFirstOrThrow({ where: { type: "exercise_batch.requested" } });
      expect(requested).toMatchObject({ actorUserId: teacher.id, targetType: "EXERCISE_BATCH", targetId: batchId });
      expect(requested.metadata).toEqual({
        executionId: execution.id,
        difficulty: "INTERMEDIATE",
        total: 10,
        openAnswer: 3,
        multipleChoice: 4,
        code: 3,
        trickQuestions: 2,
        languageKey: "java",
        distribution: "MANUAL",
        regeneratedFromId: null,
      });

      scriptGeneration(t.provider, batchId, validGeneratedBatch({ difficulty: "INTERMEDIATE", counts: { OPEN_ANSWER: 3, MULTIPLE_CHOICE: 4, CODE: 3 }, trickQuestions: 2, language: "Java" }));
      await drain(t);

      const detail = await api(t, { cookie }).get(`/api/exercise-batches/${batchId}`);
      expect(detail.status).toBe(200);
      expect(detail.body.batch).toMatchObject({ status: "GENERATED", pendingReview: 10, failureCode: null });
      const exercises = detail.body.exercises as { type: string; status: string; origin: string; difficulty: string; topic: { syllabusItemId: string }; language: { id: string } | null; isTrickQuestion: boolean; batchId: string }[];
      expect(exercises).toHaveLength(10);
      expect(exercises.filter((e) => e.type === "OPEN_ANSWER")).toHaveLength(3);
      expect(exercises.filter((e) => e.type === "MULTIPLE_CHOICE")).toHaveLength(4);
      expect(exercises.filter((e) => e.type === "CODE")).toHaveLength(3);
      expect(exercises.filter((e) => e.isTrickQuestion)).toHaveLength(2);
      const java = await languageId(t, "java");
      for (const exercise of exercises) {
        expect(exercise).toMatchObject({ status: "DRAFT", origin: "AI_GENERATED", difficulty: "INTERMEDIATE", topic: { syllabusItemId: topic.itemId }, batchId });
        if (exercise.type === "CODE") expect(exercise.language?.id).toBe(java);
      }
      const proposal = await t.prisma.aiProposal.findUniqueOrThrow({ where: { executionId: execution.id } });
      expect(proposal).toMatchObject({ proposalType: "EXERCISE_GENERATION", targetResourceId: batchId, status: "READY_FOR_REVIEW" });
      expect(proposal.itemIds).toHaveLength(10);
      const generated = await t.prisma.auditEvent.findFirstOrThrow({ where: { type: "exercise_batch.generated" } });
      expect(generated).toMatchObject({ actorType: "SYSTEM", targetType: "EXERCISE_BATCH", targetId: batchId, metadata: { executionId: execution.id, exercises: 10 } });

      const list = await api(t, { cookie }).get("/api/exercise-batches");
      expect(list.body.items.map((item: { id: string; status: string }) => [item.id, item.status])).toEqual([[batchId, "GENERATED"]]);
    });

    it("010/FR-040 o que a IA gera usa a linguagem da ementa, não a que a resposta escreve", async () => {
      const res = await requestBatch(t, cookie, batchRequest(topic, { total: 3, types: ["CODE"] }));
      scriptGeneration(t.provider, res.body.id, validGeneratedBatch({ difficulty: "INTERMEDIATE", counts: { OPEN_ANSWER: 0, MULTIPLE_CHOICE: 0, CODE: 3 }, trickQuestions: 0, language: "Java" }));
      await drain(t);
      const rows = await t.prisma.exercise.findMany({ where: { generationBatchId: res.body.id } });
      expect(rows.map((row) => row.languageId)).toEqual(Array(3).fill(topic.languageId));
    });
  });

  describe("010/US2-2 010/FR-017 tópico inválido → recusado antes de qualquer chamada, sem revelar", () => {
    it("tópico inexistente, de outra revisão ou de outro professor → 404", async () => {
      const other = await createUser(t, { roles: ["TEACHER"] });
      const foreign = await createConfirmedTopic(t, other.id);
      const second = await createConfirmedTopic(t, teacher.id);
      for (const body of [
        batchRequest(topic, { syllabusItemId: randomUUID() }),
        batchRequest(topic, { syllabusRevisionId: second.revision.id }),
        batchRequest(foreign),
        batchRequest({ revision: foreign.revision, itemId: topic.itemId }),
      ]) {
        const res = await requestBatch(t, cookie, body);
        expect({ status: res.status, code: res.body.code }).toEqual({ status: 404, code: "NOT_FOUND" });
      }
      await nothingRequested();
    });

    it("sem tópico → 400", async () => {
      const { syllabusItemId: _, ...withoutTopic } = batchRequest(topic);
      expect((await requestBatch(t, cookie, withoutTopic)).status).toBe(400);
      await nothingRequested();
    });

    it("revisão em rascunho → 422 REVISION_NOT_CONFIRMED", async () => {
      const subject = await createSubject(t, teacher.id);
      const document = await createSyllabusDocument(t, subject.id, { status: "PROCESSED" });
      const revision = await t.prisma.syllabusRevision.create({ data: { documentId: document.id, number: 1, status: "DRAFT", source: "MANUAL" } });
      const group = await t.prisma.syllabusGroup.create({ data: { revisionId: revision.id, position: 1 } });
      const item = await t.prisma.syllabusItem.create({ data: { revisionId: revision.id, groupId: group.id, position: 1, text: "Rascunho" } });
      const res = await requestBatch(t, cookie, batchRequest({ revision, itemId: item.id }));
      expect({ status: res.status, code: res.body.code }).toEqual({ status: 422, code: "REVISION_NOT_CONFIRMED" });
      await nothingRequested();
    });

    it("disciplina inativa → 409 SUBJECT_ARCHIVED", async () => {
      const inactive = await createConfirmedTopic(t, teacher.id, { subjectStatus: "INACTIVE" });
      const res = await requestBatch(t, cookie, batchRequest(inactive));
      expect({ status: res.status, code: res.body.code }).toEqual({ status: 409, code: "SUBJECT_ARCHIVED" });
      await nothingRequested();
    });
  });

  it("010/US2-8 código pedido numa ementa sem linguagem → 422 SYLLABUS_LANGUAGE_REQUIRED; sem código, o pedido segue", async () => {
    const noLanguage = await createConfirmedTopic(t, teacher.id, { languageKey: null });
    const res = await requestBatch(t, cookie, batchRequest(noLanguage, { types: ["OPEN_ANSWER", "CODE"] }));
    expect({ status: res.status, code: res.body.code }).toEqual({ status: 422, code: "SYLLABUS_LANGUAGE_REQUIRED" });
    await nothingRequested();
    const withoutCode = await requestBatch(t, cookie, batchRequest(noLanguage));
    expect(withoutCode.status).toBe(202);
    expect(withoutCode.body.language).toBeNull();
  });

  it.each([
    ["model", { model: "openai/gpt-5" }],
    ["tier", { tier: "ADVANCED" }],
    ["task", { task: "exercise-generation" }],
    ["provider", { provider: "openrouter" }],
    ["language", { language: "Java" }],
    ["texto livre no lugar do tópico", { topic: "Herança em Java" }],
  ])("010/US2-3 campo %s → 400, nada pedido", async (_, extra) => {
    const res = await requestBatch(t, cookie, { ...batchRequest(topic), ...extra });
    expect({ status: res.status, code: res.body.code }).toEqual({ status: 400, code: "VALIDATION_ERROR" });
    await nothingRequested();
  });

  describe("010/US2-4 010/FR-019 distribuição", () => {
    it("automática: 10 em 3 tipos → 4, 3 e 3", async () => {
      const res = await requestBatch(t, cookie, batchRequest(topic, { total: 10, types: ["OPEN_ANSWER", "MULTIPLE_CHOICE", "CODE"] }));
      expect(res.status).toBe(202);
      expect(res.body).toMatchObject({ counts: { OPEN_ANSWER: 4, MULTIPLE_CHOICE: 3, CODE: 3 }, distribution: "AUTO" });
    });

    it("manual com soma diferente do total → 400", async () => {
      const res = await requestBatch(
        t,
        cookie,
        batchRequest(topic, { total: 5, types: ["OPEN_ANSWER", "MULTIPLE_CHOICE"], distribution: { mode: "MANUAL", counts: { OPEN_ANSWER: 2, MULTIPLE_CHOICE: 2 } } }),
      );
      expect(res.status).toBe(400);
      await nothingRequested();
    });
  });

  describe("010/US2-5 010/FR-020 pegadinhas", () => {
    const manual = (multipleChoice: number, trickQuestions: number) =>
      batchRequest(topic, {
        total: multipleChoice + 1,
        types: ["OPEN_ANSWER", "MULTIPLE_CHOICE"],
        distribution: { mode: "MANUAL", counts: { OPEN_ANSWER: 1, MULTIPLE_CHOICE: multipleChoice } },
        trickQuestions,
      });

    it("5 de múltipla escolha e 3 pegadinhas → aceito", async () => {
      expect((await requestBatch(t, cookie, manual(5, 3))).status).toBe(202);
    });

    it.each([
      ["2 de múltipla escolha e 3 pegadinhas", () => manual(2, 3)],
      ["4 pegadinhas", () => manual(5, 4)],
      ["pegadinha sem múltipla escolha", () => batchRequest(topic, { trickQuestions: 1 })],
    ])("%s → 400", async (_, body) => {
      expect((await requestBatch(t, cookie, body())).status).toBe(400);
      await nothingRequested();
    });
  });

  describe("010/FR-021 idempotência", () => {
    it("mesma chave e mesmo pedido → o mesmo lote (200); outra configuração com a mesma chave → 409", async () => {
      const body = batchRequest(topic);
      const first = await requestBatch(t, cookie, body);
      const again = await requestBatch(t, cookie, body);
      expect(first.status).toBe(202);
      expect(again.status).toBe(200);
      expect(again.body.id).toBe(first.body.id);
      const other = await requestBatch(t, cookie, { ...body, difficulty: "ADVANCED" });
      expect({ status: other.status, code: other.body.code }).toEqual({ status: 409, code: "AI_IDEMPOTENCY_KEY_REUSED" });
      expect(await t.prisma.exerciseGenerationBatch.count()).toBe(1);
      expect(await t.prisma.aiExecution.count()).toBe(1);
    });

    it("pedidos simultâneos com a mesma chave → um lote e uma execução", async () => {
      const body = batchRequest(topic);
      const results = await Promise.all([requestBatch(t, cookie, body), requestBatch(t, cookie, body), requestBatch(t, cookie, body)]);
      expect(results.map((res) => res.status).sort()).toEqual([200, 200, 202]);
      expect(new Set(results.map((res) => res.body.id)).size).toBe(1);
      expect(await t.prisma.exerciseGenerationBatch.count()).toBe(1);
      expect(await t.prisma.aiExecution.count()).toBe(1);
    });
  });

  it("gerar de novo: o novo lote aponta o anterior; um lote de outro professor → 404", async () => {
    const first = await requestBatch(t, cookie, batchRequest(topic));
    const again = await requestBatch(t, cookie, batchRequest(topic, { regeneratedFromId: first.body.id }));
    expect(again.status).toBe(202);
    expect(again.body.regeneratedFromId).toBe(first.body.id);
    const other = await createUser(t, { roles: ["TEACHER"] });
    const otherCookie = await loginAs(t, other);
    const otherTopic = await createConfirmedTopic(t, other.id);
    const refused = await requestBatch(t, otherCookie, batchRequest(otherTopic, { regeneratedFromId: first.body.id }));
    expect(refused.status).toBe(404);
    expect((await api(t, { cookie: otherCookie }).get(`/api/exercise-batches/${first.body.id}`)).status).toBe(404);
  });

  describe("010/US2-7 010/FR-025 indisponível → recusado, e a criação manual continua", () => {
    it("agente desabilitado: disponibilidade AGENT_DISABLED e 409 AI_AGENT_DISABLED", async () => {
      const admin = await createUser(t, { roles: ["ADMIN"] });
      await t.get(AiOperationsService).changeAgentStatus({ userId: admin.id, requestId: null }, EXERCISE_GENERATOR_KEY, "DISABLED");
      expect((await api(t, { cookie }).get("/api/exercise-generation/availability")).body).toEqual({ availability: "AGENT_DISABLED" });
      const res = await requestBatch(t, cookie, batchRequest(topic));
      expect({ status: res.status, code: res.body.code }).toEqual({ status: 409, code: "AI_AGENT_DISABLED" });
      await nothingRequested();
      const manual = await api(t, { cookie }).post("/api/exercises", {
        type: "OPEN_ANSWER",
        statement: "Manual",
        explanation: "Explicação",
        difficulty: "BASIC",
        cognitiveObjective: "UNDERSTAND",
        expectedAnswer: "Sim",
        status: "APPROVED",
      });
      expect(manual.status).toBe(201);
    });

    it("sem modelo utilizável: disponibilidade MODEL_UNAVAILABLE e 503 AI_MODEL_UNAVAILABLE", async () => {
      const admin = await createUser(t, { roles: ["ADMIN"] });
      await t.get(AiOperationsService).changeModelConfigStatus({ userId: admin.id, requestId: null }, TEST_EXERCISE_MODEL_CONFIG.key, "DISABLED");
      expect((await api(t, { cookie }).get("/api/exercise-generation/availability")).body).toEqual({ availability: "MODEL_UNAVAILABLE" });
      const res = await requestBatch(t, cookie, batchRequest(topic));
      expect({ status: res.status, code: res.body.code }).toEqual({ status: 503, code: "AI_MODEL_UNAVAILABLE" });
      await nothingRequested();
    });

    it("IA pausada (intervalo do worker 0, como nos testes) → PAUSED, e o pedido ainda fica na fila", async () => {
      expect((await api(t, { cookie }).get("/api/exercise-generation/availability")).body).toEqual({ availability: "PAUSED" });
      expect((await requestBatch(t, cookie, batchRequest(topic))).status).toBe(202);
    });
  });
});

describe("010/US2 010/FR-022 limite por professor por hora", () => {
  let t: AiTestApp;

  beforeAll(async () => {
    t = await createExerciseAiApp({ config: limits({ exerciseAiPerHour: 2 }) });
    await resetAiDb(t);
  });
  afterAll(() => t.close());

  it("o terceiro pedido na hora → 429, sem lote nem execução", async () => {
    const teacher = await createUser(t, { roles: ["TEACHER"] });
    const cookie = await loginAs(t, teacher);
    const topic = await createConfirmedTopic(t, teacher.id);
    expect((await requestBatch(t, cookie, batchRequest(topic))).status).toBe(202);
    expect((await requestBatch(t, cookie, batchRequest(topic))).status).toBe(202);
    const third = await requestBatch(t, cookie, batchRequest(topic));
    expect({ status: third.status, code: third.body.code }).toEqual({ status: 429, code: "RATE_LIMITED" });
    expect(await t.prisma.exerciseGenerationBatch.count()).toBe(2);
    const limited = await t.prisma.auditEvent.findFirstOrThrow({ where: { type: "ai_execution.rate_limited" } });
    expect(limited.metadata).toEqual({ scope: "exercise-ai" });
  });
});
